function melbourneDate() {
  const parts = new Intl.DateTimeFormat("en-AU", {
    timeZone: "Australia/Melbourne",
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  }).formatToParts(new Date());
  const get = (type) => parts.find((part) => part.type === type).value;
  return `${get("year")}-${get("month")}-${get("day")}`;
}

function countResources(data) {
  const countries = Object.values(data.countries || {});
  let resourceRecords = 0;
  let verifiedRecords = 0;
  let contactMethods = 0;

  for (const country of countries) {
    for (const resource of country.resources || []) {
      resourceRecords++;
      if (resource.verified) verifiedRecords++;
      for (const key of ["phone", "text", "chat_url", "email", "whatsapp", "website"]) {
        if (resource[key]) contactMethods++;
      }
    }
  }

  return {
    countryCount: countries.length,
    resourceRecords,
    verifiedRecords,
    contactMethods,
  };
}

function getTestSummary() {
  const result = spawnSync("node", ["test/run.js"], {
    cwd: root,
    encoding: "utf8",
  });
  const output = `${result.stdout || ""}\n${result.stderr || ""}`;
  const match = output.match(/(\d+) passed,\s*(\d+) failed/);

  if (!match) {
    throw new Error("Could not parse test summary from test/run.js output.");
  }

  const passed = Number(match[1]);
  const failed = Number(match[2]);
  if (result.status !== 0 || failed > 0) {
    throw new Error(`Test suite failed while updating cheat sheet: ${passed} passed, ${failed} failed.`);
  }

  return { passed, failed };
}

